#!/usr/bin/env python3
"""Configures the build of one game version.

    python3 configure.py --version us
    ninja

This writes build.ninja and objdiff.json. ninja then extracts the original objects, compiles
src/, links the game and checks its SHA-1 against config/<version>/build.sha1.
`objdiff-cli report generate` reads objdiff.json to write the progress report.
"""

import argparse
import json
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parent

# Version id -> the VERSION define (include/version.h). CI uploads each version's report as
# the artifact <version id>_report.
VERSIONS = {"us": 0, "eu": 1}
DEFAULT_VERSION = "us"

ALL = tuple(VERSIONS)

# Progress categories: each unit counts toward the categories it lists.
PROGRESS_CATEGORIES = [
    {"id": "game", "name": "Game"},
    {"id": "sdk", "name": "SDK"},
]


class Unit(NamedTuple):
    name: str
    # The decompiled source, or None while there is none (base_path null).
    source: str | None
    category: str
    # Versions where the unit matches exactly, so the build links the object built from
    # source in place of the original (objdiff's "complete").
    linked: tuple[str, ...] = ()


# Every object linked into the game, in link order. List all of them, decompiled or not, so
# the totals cover the whole game.
UNITS = [
    Unit("game/main", "src/game/main.c", "game", linked=ALL),
    Unit("game/player", "src/game/player.c", "game"),
    Unit("game/save", None, "game"),
    Unit("sdk/os", "src/sdk/os.c", "sdk", linked=ALL),
    Unit("sdk/math", "src/sdk/math.c", "sdk"),
]

DEFAULT_CROSS = "powerpc-linux-gnu-"

# The original objects were built with exactly these flags; a different compiler or flag
# changes the code and breaks the matches.
CFLAGS = [
    "-O2",
    "-mcpu=750",
    "-fno-inline",
    "-fno-pie",
    "-fno-pic",
    "-fno-stack-protector",
    "-fno-asynchronous-unwind-tables",
    "-fno-ident",
    "-ffreestanding",
    "-nostdinc",
    "-Wall",
    "-Iinclude",
]


def cflags(version: str) -> list[str]:
    return CFLAGS + [f"-DVERSION={VERSIONS[version]}"]


def orig_path(version: str, unit: Unit) -> str:
    """The original object, as the owner's game files would provide it."""
    return f"orig/{version}/obj/{unit.name}.o"


def target_path(version: str, unit: Unit) -> str:
    """The extracted original object: what the decompilation has to match."""
    return f"build/{version}/obj/{unit.name}.o"


def base_path(version: str, unit: Unit) -> str | None:
    """The object built from src/, or None without source."""
    if unit.source is None:
        return None
    return f"build/{version}/{Path(unit.source).with_suffix('.o').as_posix()}"


def link_inputs(version: str) -> list[str]:
    """Linked units come from source; every other unit is still the original object."""
    return [
        base_path(version, u) if version in u.linked else target_path(version, u)
        for u in UNITS
    ]


def objdiff_config(version: str) -> dict:
    units = []
    for unit in UNITS:
        metadata = {
            "complete": version in unit.linked,
            "progress_categories": [unit.category],
        }
        if unit.source is not None:
            metadata["source_path"] = unit.source
        units.append(
            {
                "name": unit.name,
                "target_path": target_path(version, unit),
                "base_path": base_path(version, unit),
                "metadata": metadata,
            }
        )
    return {
        "min_version": "3.0.0",
        "custom_make": "ninja",
        "build_target": False,
        "build_base": True,
        "watch_patterns": ["*.c", "*.h"],
        "units": units,
        "progress_categories": PROGRESS_CATEGORIES,
    }


def build_ninja(version: str, cross: str) -> str:
    out = f"build/{version}"
    elf, binary, ok = f"{out}/game.elf", f"{out}/game.bin", f"{out}/game.ok"
    lines = [
        f"# Generated by configure.py for version {version}; edit configure.py instead.",
        "ninja_required_version = 1.10",
        f"cc = {cross}gcc",
        f"ld = {cross}ld",
        f"objcopy = {cross}objcopy",
        f"cflags = {' '.join(cflags(version))}",
        "",
        "rule configure",
        f"  command = python3 configure.py --version {version} --cross {cross}",
        "  generator = 1",
        "  description = CONFIGURE",
        "",
        "# Real projects split the objects out of the owner's game files here.",
        "rule extract",
        "  command = cp $in $out",
        "  description = EXTRACT $out",
        "",
        "rule cc",
        "  command = $cc $cflags -MMD -MF $out.d -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CC $out",
        "",
        "rule link",
        "  command = $ld -T tools/link.ld -o $out $in",
        "  description = LINK $out",
        "",
        "rule binary",
        "  command = $objcopy -O binary $in $out",
        "  description = OBJCOPY $out",
        "",
        "rule check",
        "  command = sha1sum --quiet -c $in && touch $out",
        "  description = CHECK $out",
        "",
        "build build.ninja objdiff.json: configure configure.py",
        "",
    ]
    objects = []
    for unit in UNITS:
        target = target_path(version, unit)
        lines.append(f"build {target}: extract {orig_path(version, unit)}")
        objects.append(target)
        base = base_path(version, unit)
        if base is not None:
            lines.append(f"build {base}: cc {unit.source}")
            objects.append(base)
    lines += [
        "",
        f"build {elf}: link {' '.join(link_inputs(version))} | tools/link.ld",
        f"build {binary}: binary {elf}",
        f"build {ok}: check config/{version}/build.sha1 | {binary}",
        "",
        f"default {ok} {' '.join(objects)}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", choices=VERSIONS, default=DEFAULT_VERSION)
    parser.add_argument(
        "--cross",
        default=DEFAULT_CROSS,
        help=f"cross toolchain prefix (default {DEFAULT_CROSS})",
    )
    args = parser.parse_args()

    (ROOT / "build.ninja").write_text(build_ninja(args.version, args.cross), newline="\n")
    config = json.dumps(objdiff_config(args.version), indent=2) + "\n"
    (ROOT / "objdiff.json").write_text(config, newline="\n")
    print(f"Configured version {args.version}: run ninja")


if __name__ == "__main__":
    main()
